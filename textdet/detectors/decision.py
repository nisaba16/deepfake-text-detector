@dataclass
class DecisionTokens:
    """Special token ids of a decision model's tokenizer (mmBERT: <bos>=CLS, <eos>=SEP, <mask>, <pad>)."""
    cls: int
    sep: int
    mask: int
    pad: int
    mask_text: str

    @classmethod
    def from_tokenizer_dir(cls, directory: Path) -> "DecisionTokens":
        from tokenizers import Tokenizer
        tok = Tokenizer.from_file(str(directory / "tokenizer.json"))
        cfg = json.loads((directory / "tokenizer_config.json").read_text())

        def token(key):
            value = cfg[key]
            content = value["content"] if isinstance(value, dict) else value
            return content, tok.token_to_id(content)

        mask_text, mask = token("mask_token")
        return cls(cls=token("cls_token")[1], sep=token("sep_token")[1], mask=mask, pad=token("pad_token")[1],
                   mask_text=mask_text)


def encode_prefix(tokenizer, special: DecisionTokens, question: str, options: Sequence[str], qtype: str,
                  head_length: int = 256) -> Tuple[List[int], List[int]]:
    """Token ids of '[CLS] <qtype> question: ... [SEP] [MASK] option ... [SEP]' and the [MASK] positions.

    Same truncation rules as julia.data.sequence (non-strict): options keep at most 48 tokens, and the question
    and options share a budget of head_length tokens.
    """
    clean = lambda text: text.replace(special.mask_text, " ")
    encode = lambda text: tokenizer.encode(text, add_special_tokens=False).ids
    head = encode(f"{qtype} question: {clean(question)}")
    option_ids = [encode(" " + clean(x)) for x in options]
    opts = [[special.mask] + x[:48] for x in option_ids]
    budget = head_length - sum(map(len, opts))
    if budget < 16:
        per_option = max(4, (head_length - 16) // len(opts))
        opts = [x[:per_option] for x in opts]
        budget = head_length - sum(map(len, opts))
    ids = [special.cls] + head[:max(8, budget)] + [special.sep]
    markers = []
    for option in opts:
        markers.append(len(ids))
        ids.extend(option)
    ids.append(special.sep)
    return ids, markers


def build_julia_model(checkpoint_dir: Path, memory_map: bool = True):
    """JuliaDecisionModel from julia/model.py (Apache-2.0, Supersonic Labs), inference only.

    Also loads Laya checkpoints (rl_agent_config.json): the two share the architecture.
    """
    import torch
    from torch import nn
    from safetensors.torch import load_file
    from transformers import AutoConfig, AutoModel

    class JuliaDecisionModel(nn.Module):
        def __init__(self, encoder, head_layers=2, n_act=2, dropout=.1):
            super().__init__()
            self.encoder = encoder
            width = encoder.config.hidden_size
            layer = nn.TransformerEncoderLayer(width, max(1, width // 64), 4 * width,
                                               dropout, batch_first=True, norm_first=True)
            self.head = nn.TransformerEncoder(layer, head_layers, enable_nested_tensor=False) if head_layers else None
            self.type_emb = nn.Embedding(3, width)
            self.scorer = nn.Sequential(nn.LayerNorm(width), nn.Linear(width, width), nn.GELU(), nn.Linear(width, 1))
            self.act_head = nn.Sequential(nn.Linear(width + 4, 256), nn.GELU(), nn.Linear(256, n_act))
            self.register_buffer('temperature', torch.ones(3))

        def forward(self, input_ids, attention_mask, marker_pos, marker_mask, qtype):
            hidden = self.encoder(input_ids=input_ids, attention_mask=attention_mask).last_hidden_state
            hidden = hidden + self.type_emb(qtype)[:, None, :]
            if self.head is not None:
                padding = ~attention_mask.bool()
                for layer in self.head.layers:
                    hidden = layer(hidden, src_key_padding_mask=padding)
            hidden = hidden.gather(1, marker_pos[:, :, None].expand(-1, -1, hidden.shape[-1]))
            scores = self.scorer(hidden).squeeze(-1).float()
            return scores.masked_fill(~marker_mask, -1e4)

    root = Path(checkpoint_dir)
    if (root / "julia_config.json").exists():
        config = json.loads((root / "julia_config.json").read_text())
        settings = {k: config[k] for k in ("head_layers", "n_act", "dropout")}
    else:
        config = json.loads((root / "rl_agent_config.json").read_text())
        settings = dict(head_layers=config["head_layers"], n_act=len(config.get("act_costs", {})) + 1)
    encoder_config = AutoConfig.from_pretrained(root / "encoder")
    encoder_config.reference_compile = False
    rope = getattr(encoder_config, "rope_parameters", None)
    if isinstance(rope, dict) and "full_attention" in rope:
        # transformers 4.x reads the RoPE bases from these two attributes instead of rope_parameters
        encoder_config.global_rope_theta = rope["full_attention"]["rope_theta"]
        encoder_config.local_rope_theta = rope.get("sliding_attention", rope["full_attention"])["rope_theta"]
    encoder = AutoModel.from_config(encoder_config, attn_implementation="sdpa")
    model = JuliaDecisionModel(encoder, **settings)
    state = load_file(str(root / "model.safetensors"))
    # Keep the dtype of the checkpoint (Laya is fp16): cast to the model's fp32 after loading
    state = {k: v.float() if v.is_floating_point() else v for k, v in state.items()} if not memory_map else state
    model.load_state_dict(state, strict=True, assign=memory_map)
    return model.float().eval()


def download_decision_checkpoint(checkpoint: str, revision: Optional[str] = None,
                                 subfolder: Optional[str] = None) -> Path:
    """Local directory of a decision-model checkpoint (downloads only the files inference needs)."""
    path = Path(checkpoint)
    if path.exists():
        return path / subfolder if subfolder else path
    from huggingface_hub import snapshot_download
    prefix = f"{subfolder}/" if subfolder else ""
    patterns = [f"{prefix}{p}" for p in ("model.safetensors", "*.json", "encoder/*", "tokenizer/*")]
    root = Path(snapshot_download(checkpoint, revision=revision, allow_patterns=patterns))
    return root / subfolder if subfolder else root


class JuliaDetector(DecisionDetector):
    """Zero-shot AI-text detector on Julia 1 (or any checkpoint in its format). Labels: 0=human, 1=AI."""

    def __init__(self, checkpoint: str = JULIA_CHECKPOINT, revision: Optional[str] = None,
                 questions: Optional[Dict[str, Tuple[Dict, bool]]] = None, device: Optional[str] = None,
                 batch_size: int = 8, max_length: int = 1024, head_length: int = 256):
        """
        Args:
            checkpoint: Hugging Face repo or local directory of a Julia checkpoint
            max_length: tokens per sequence, question included (Julia's published accuracy used 1024;
                the model accepts up to 8192)
            head_length: token budget of the question and its options (Julia's default)
        """
        super().__init__(questions)
        import torch
        from tokenizers import Tokenizer
        for qid, (question, _) in self.questions.items():
            if question.get("type", "noul") != "noul":
                raise ValueError(f"{qid}: only noul (yes/no) questions make a detector")
            if "labels" in question:
                warnings.warn(f"{qid}: Julia shows the option descriptions only; 'labels' is ignored")
        self.checkpoint, self.revision = checkpoint, revision
        self.batch_size, self.max_length, self.head_length = batch_size, max_length, head_length
        if device is None or (str(device).startswith("cuda") and not torch.cuda.is_available()):
            device = "cuda" if torch.cuda.is_available() else "cpu"
        self.device = torch.device(device)
        self.root = download_decision_checkpoint(checkpoint, revision)
        tok_dir = self.root / "tokenizer"
        self.tokenizer = Tokenizer.from_file(str(tok_dir / "tokenizer.json"))
        self.special = DecisionTokens.from_tokenizer_dir(tok_dir)
        self.model = build_julia_model(self.root).to(self.device)
        self.prefixes = {qid: encode_prefix(self.tokenizer, self.special, q["instructions"], noul_options(q),
                                            "noul", head_length) for qid, (q, _) in self.questions.items()}

    def describe(self):
        return {"detector": "julia", "checkpoint": self.checkpoint, "revision": self.revision,
                "max_len": self.max_length}

    def encode(self, text: str, qid: str) -> Tuple[List[int], List[int]]:
        """Full sequence and [MASK] positions of one text for one question (julia.data.sequence)."""
        prefix, markers = self.prefixes[qid]
        state = self.tokenizer.encode(text.replace(self.special.mask_text, " "), add_special_tokens=False).ids
        room = self.max_length - len(prefix) - 1
        if room < 1:
            raise ValueError("The question leaves no room for the text: raise max_length")
        return prefix + state[:room] + [self.special.sep], markers

    def option_logits(self, texts: Sequence[str], qid: str):
        """Raw [false, true] option scores, (n_texts, 2)."""
        import torch
        rows = [self.encode(t, qid) for t in texts]
        length = min(self.max_length, ((max(len(ids) for ids, _ in rows) + 7) // 8) * 8)
        ids = torch.full((len(rows), length), self.special.pad, dtype=torch.long)
        attention = torch.zeros_like(ids)
        for i, (row, _) in enumerate(rows):
            ids[i, :len(row)] = torch.tensor(row)
            attention[i, :len(row)] = 1
        markers = torch.tensor([m for _, m in rows], dtype=torch.long)
        with torch.inference_mode():
            logits = self.model(ids.to(self.device), attention.to(self.device), markers.to(self.device),
                                torch.ones_like(markers, dtype=torch.bool).to(self.device),
                                torch.full((len(rows),), QTYPES["noul"], dtype=torch.long, device=self.device))
        return logits.float().cpu().numpy()

    def predict_scores(self, texts: Sequence[str], show_progress: bool = True):
        if len(texts) == 0:
            empty = np.empty((0, len(self.qids)))
            return empty, empty.copy()
        # Sort by length so batches pad little, then restore the input order
        order = np.argsort([len(t) for t in texts])
        z_true = np.zeros((len(texts), len(self.qids)))
        batches = list(batched(order, self.batch_size))
        for idx in tqdm(batches, disable=not show_progress, desc="Julia decision model"):
            chunk = [texts[i] for i in idx]
            for j, qid in enumerate(self.qids):
                logits = self.option_logits(chunk, qid)
                z_true[idx, j] = logits[:, 1] - logits[:, 0]
        p_true = 1.0 / (1.0 + np.exp(-np.clip(z_true, -50, 50)))  # softmax over the two options
        ai_is_true = np.array([self.questions[q][1] for q in self.qids])
        return self._to_ai(p_true, z_true, ai_is_true)

    def close(self):
        import torch
        del self.model
        if torch.cuda.is_available():
            torch.cuda.empty_cache()


