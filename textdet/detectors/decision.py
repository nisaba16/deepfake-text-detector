"""
Jev-like zero-shot detectors: ask a "System 1" decision model whether a text was generated by an AI.

Jev (TypeSafe's hosted decision API) answers typed questions about a text in one forward pass of an
encoder-only model, with no text generation. Two open models of that family are supported:

    Laya     convaiinnovations/laya: ModernBERT-large (421M parameters, 804 MiB fp16), 512 tokens.
             Run through the `laya` package (pip install laya, Python >= 3.10). Kept as the reference.
    Julia 1  SupersonicLabs/Julia-1: mmBERT-small (144M parameters, 550 MiB fp32), up to 8192 tokens,
             Apache-2.0, an official ONNX build for the browser. Run natively here (no extra package):
             the model class and the input serialization below reproduce julia/model.py and julia/data.py.

Both read one sequence per question

    [CLS] noul question: <instructions> [SEP] [MASK] <false option> [MASK] <true option> [SEP] <text> [SEP]

and score the hidden state at each [MASK]; for a `noul` (yes/no) question the softmax over the two options
is P(true). Asking "was this text generated by an AI?" gives a detector that never saw our data: the
zero-shot baseline the trained detectors should beat.
"""
from __future__ import annotations

import json
import warnings
from contextlib import contextmanager
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Tuple

import numpy as np
from tqdm import tqdm

from .base import Detector, Scores, batched, safe_name

LAYA_CHECKPOINT = "convaiinnovations/laya"
JULIA_CHECKPOINT = "SupersonicLabs/Julia-1"
DEFAULT_CHECKPOINT = LAYA_CHECKPOINT  # historical default of scripts/evaluate_jev_baseline.py

QTYPES = {"choice": 0, "score": 1, "noul": 2}

# name -> (question, ai_is_true). ai_is_true=False marks a question that asks whether a human wrote
# the text, so P(AI) = 1 - P(true).
QUESTION_PRESETS: Dict[str, Tuple[Dict, bool]] = {
    "ai_generated": ({
        "type": "noul",
        "instructions": "Was this text generated by an AI language model rather than written by a human?",
        "criteria": {"true": "generated by an AI model such as ChatGPT", "false": "written by a human"},
    }, True),
    # Same question with neutral option labels: Laya's README warns that the words "true"/"false"
    # can make the model follow the label instead of the text. (Laya only: Julia shows no labels.)
    "ai_generated_ab": ({
        "type": "noul",
        "instructions": "Was this text generated by an AI language model rather than written by a human?",
        "criteria": {"true": "generated by an AI model such as ChatGPT", "false": "written by a human"},
        "labels": {"true": "A", "false": "B"},
    }, True),
    # Opposite polarity: averaged with "ai_generated" it cancels a bias towards answering "true".
    "human_written": ({
        "type": "noul",
        "instructions": "Was this text written by a human rather than generated by an AI language model?",
        "criteria": {"true": "written by a human", "false": "generated by an AI model such as ChatGPT"},
    }, False),
}


def build_questions(names: Sequence[str] = ("ai_generated",), instructions: Optional[str] = None,
                    true_criterion: Optional[str] = None,
                    false_criterion: Optional[str] = None) -> Dict[str, Tuple[Dict, bool]]:
    """Presets by name, plus a 'custom' noul question whose 'true' answer means AI-generated."""
    questions = {name: QUESTION_PRESETS[name] for name in names}
    if instructions:
        question = {"type": "noul", "instructions": instructions}
        criteria = {k: v for k, v in (("true", true_criterion), ("false", false_criterion)) if v}
        if criteria:
            question["criteria"] = criteria
        questions["custom"] = (question, True)
    if not questions:
        raise ValueError("No question to ask: pass question presets and/or custom instructions")
    return questions


def noul_options(question: Dict) -> List[str]:
    """The [false, true] option texts of a noul question, as Julia renders them (julia/typed.py)."""
    criteria = question.get("criteria")
    if criteria is None:
        return ["false", "true"]
    if set(criteria) != {"false", "true"}:
        raise ValueError("noul criteria must describe exactly 'false' and 'true'")
    return [criteria["false"], criteria["true"]]


class DecisionDetector(Detector):
    """Common part of the Jev-like detectors: one head per question, plus their mean with several."""
    analysis = "jev"
    train_dataset = "zeroshot"

    def __init__(self, questions: Optional[Dict[str, Tuple[Dict, bool]]] = None):
        self.questions = questions or {"ai_generated": QUESTION_PRESETS["ai_generated"]}
        self.qids = list(self.questions)

    @property
    def heads(self) -> list:
        return self.qids + (["ensemble_mean"] if len(self.qids) > 1 else [])

    def predict_scores(self, texts: Sequence[str], show_progress: bool = True) -> Tuple[np.ndarray, np.ndarray]:
        """(p_ai, log_odds), each (n_texts, n_questions) with columns in `self.qids` order."""
        raise NotImplementedError

    def score(self, texts: Sequence[str]) -> Dict[str, Scores]:
        p_ai, log_odds = self.predict_scores(texts)
        out = {qid: Scores(p_ai[:, j], log_odds[:, j]) for j, qid in enumerate(self.qids)}
        if len(self.qids) > 1:
            # Probabilities and log-odds averaged, as the historical baseline script did
            out["ensemble_mean"] = Scores(p_ai.mean(axis=1), log_odds.mean(axis=1))
        return out

    def question_column(self, head: str) -> str:
        return json.dumps(self.questions[head][0]) if head in self.questions else " + ".join(self.qids)

    @staticmethod
    def _to_ai(p_true: np.ndarray, z_true: np.ndarray, ai_is_true: np.ndarray):
        return np.where(ai_is_true, p_true, 1.0 - p_true), np.where(ai_is_true, z_true, -z_true)


