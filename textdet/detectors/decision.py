@contextmanager
def _capture_option_logits(agent, sink: List[np.ndarray]):
    """Collect the raw option logits of every forward pass the agent runs inside the block.

    Laya only returns noul rounded to 4 decimals, which ties saturated answers and understates
    ROC-AUC, so the unrounded logits are read from `Agent._forward`. It is private: callers check
    what was captured against the public answers and fall back to those when they disagree.
    """
    forward = getattr(agent, "_forward", None)
    if forward is None:
        yield
        return
    shadowed = "_forward" in vars(agent)

    def spy(batch):
        logits, act = forward(batch)
        sink.append(np.asarray(logits, dtype=np.float64)[:, :2])
        return logits, act

    agent._forward = spy
    try:
        yield
    finally:
        if shadowed:
            agent._forward = forward
        else:
            del agent._forward


class LayaDetector(DecisionDetector):
    """Zero-shot AI-text detector on a Laya checkpoint. Labels follow the codebase: 0=human, 1=AI."""

    def __init__(
        self,
        checkpoint: str = LAYA_CHECKPOINT,
        subfolder: Optional[str] = None,
        questions: Optional[Dict[str, Tuple[Dict, bool]]] = None,
        device: Optional[str] = None,
        batch_size: int = 16,
        max_len: Optional[int] = None,
    ):
        """
        Args:
            checkpoint: Hugging Face repo or local directory of a Laya checkpoint
            subfolder: checkpoint inside the repo: None (English, ModernBERT-large, 512 tokens),
                "multilingual" (mmBERT-base, up to 8192 tokens with max_len) or "typed-decisions"
            questions: name -> (noul question, ai_is_true); defaults to the "ai_generated" preset
            device: torch device; laya falls back to CPU when it is not available
            batch_size: texts per forward pass (each text is one row per question)
            max_len: token budget per row, question included (None: the checkpoint's own)
        """
        super().__init__(questions)
        try:
            import laya
        except ImportError as e:
            raise ImportError("The Laya baseline needs the laya package: pip install laya (Python >= 3.10)") from e

        self.checkpoint, self.subfolder = checkpoint, subfolder
        self.batch_size = batch_size
        self.max_len = max_len
        self.laya_version = getattr(laya, "__version__", "unknown")
        self.agent = laya.load(checkpoint, device=device, subfolder=subfolder)
        self._warned_rounded = False

    @property
    def tag(self) -> str:
        return safe_name(self.checkpoint + (f"_{self.subfolder}" if self.subfolder else ""))

    def describe(self):
        return {"detector": "laya", "checkpoint": self.checkpoint + (f"/{self.subfolder}" if self.subfolder else ""),
                "revision": getattr(self.agent, "revision", None), "max_len": self.max_len,
                "laya_version": self.laya_version}

    def predict_scores(self, texts: Sequence[str], show_progress: bool = True) -> Tuple[np.ndarray, np.ndarray]:
        """Score texts against every question.

        Returns:
            p_ai: (n_texts, n_questions) Laya's public noul answer turned into P(AI), the calibrated
                probability to threshold
            score: (n_texts, n_questions) unrounded log-odds of AI, the same ranking as p_ai without
                the ties that rounding creates; use it for ROC-AUC
            Columns follow `self.qids`.
        """
        if len(texts) == 0:
            empty = np.empty((0, len(self.qids)))
            return empty, empty.copy()

        chunk = max(1, self.batch_size) * 8
        p_true, log_odds = [], []
        for start in tqdm(range(0, len(texts), chunk), disable=not show_progress, desc="Laya decision model"):
            p, z = self._predict_chunk(list(texts[start:start + chunk]))
            p_true.append(p)
            log_odds.append(z)
        p_true, log_odds = np.concatenate(p_true), np.concatenate(log_odds)

        ai_is_true = np.array([self.questions[qid][1] for qid in self.qids])
        return self._to_ai(p_true, log_odds, ai_is_true)

    def _predict_chunk(self, texts: List[str]) -> Tuple[np.ndarray, np.ndarray]:
        questions = {qid: self.questions[qid][0] for qid in self.qids}
        captured: List[np.ndarray] = []
        # sort_by_length stays off: the captured rows must come back in input order.
        with _capture_option_logits(self.agent, captured):
            results = self.agent.predict_batch(texts, questions, batch_size=self.batch_size, max_len=self.max_len)
        p_true = np.array([[r["answers"][qid]["noul"] for qid in self.qids] for r in results], dtype=np.float64)
        return p_true, self._log_odds(captured, p_true)

    def _log_odds(self, captured: List[np.ndarray], p_true: np.ndarray) -> np.ndarray:
        """Unrounded log-odds of P(true) per row, or the rounded answers' log-odds as a fallback."""
        n, q = p_true.shape
        if captured:
            rows = np.concatenate(captured)
            if rows.shape[0] == n * q:
                # Rows are state-major with the questions in order (laya.common.collate_items).
                z = (rows[:, 1] - rows[:, 0]).reshape(n, q)
                decided = np.abs(p_true - 0.5) > 0.01
                if np.array_equal(z[decided] > 0, p_true[decided] > 0.5):
                    return z
        if not self._warned_rounded:
            warnings.warn("Could not read the raw logits from laya (did Agent._forward change?); "
                          "scores fall back to the rounded noul answers, so saturated answers tie.")
            self._warned_rounded = True
        p = np.clip(p_true, 1e-6, 1 - 1e-6)
        return np.log(p / (1 - p))


def load_decision_detector(backend: str = "julia", checkpoint: Optional[str] = None, **kwargs) -> DecisionDetector:
    """backend 'julia' (native, default Julia 1) or 'laya' (laya package, default English Laya)."""
    if backend == "julia":
        kwargs.pop("subfolder", None)
        if "max_len" in kwargs:
            max_len = kwargs.pop("max_len")
            if max_len:
                kwargs["max_length"] = max_len
        return JuliaDetector(checkpoint or JULIA_CHECKPOINT, **kwargs)
    if backend == "laya":
        kwargs.pop("revision", None)
        return LayaDetector(checkpoint or LAYA_CHECKPOINT, **kwargs)
    raise ValueError(f"Unknown decision backend {backend!r} (use julia or laya)")
